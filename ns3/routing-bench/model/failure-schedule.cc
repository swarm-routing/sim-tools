std::string Sha256Hex(const std::string& bytes) {
    std::array<uint32_t, 8> h = {0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a,
                                 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19};
    std::string msg = bytes;
    const uint64_t bits = static_cast<uint64_t>(bytes.size()) * 8;
    msg.push_back(static_cast<char>(0x80));
    while (msg.size() % 64 != 56) msg.push_back('\0');
    for (int k = 7; k >= 0; --k) msg.push_back(static_cast<char>((bits >> (8 * k)) & 0xff));
    for (std::size_t off = 0; off < msg.size(); off += 64) {
        std::array<uint32_t, 64> w{};
        for (int t = 0; t < 16; ++t) {
            w[t] = 0;
            for (int k = 0; k < 4; ++k) {
                w[t] = (w[t] << 8) | static_cast<uint8_t>(msg[off + 4 * t + k]);
            }
        }
        for (int t = 16; t < 64; ++t) {
            const uint32_t s0 = RotR(w[t - 15], 7) ^ RotR(w[t - 15], 18) ^ (w[t - 15] >> 3);
            const uint32_t s1 = RotR(w[t - 2], 17) ^ RotR(w[t - 2], 19) ^ (w[t - 2] >> 10);
            w[t] = w[t - 16] + s0 + w[t - 7] + s1;
        }
        std::array<uint32_t, 8> v = h;
        for (int t = 0; t < 64; ++t) {
            const uint32_t s1 = RotR(v[4], 6) ^ RotR(v[4], 11) ^ RotR(v[4], 25);
            const uint32_t ch = (v[4] & v[5]) ^ (~v[4] & v[6]);
            const uint32_t t1 = v[7] + s1 + ch + kSha256K[t] + w[t];
            const uint32_t s0 = RotR(v[0], 2) ^ RotR(v[0], 13) ^ RotR(v[0], 22);
            const uint32_t maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
            const uint32_t t2 = s0 + maj;
            v = {t1 + t2, v[0], v[1], v[2], v[3] + t1, v[4], v[5], v[6]};
        }
        for (int k = 0; k < 8; ++k) h[k] += v[k];
    }
    std::ostringstream hex;
    for (uint32_t x : h) hex << std::hex << std::setw(8) << std::setfill('0') << x;
    return hex.str();
}

FailureSchedule ReadFailureSchedule(const std::string& path, uint32_t nNodes, double simTime) {
    std::ifstream in(path, std::ios::binary);
    NS_ABORT_MSG_UNLESS(in, "--failures='" << path << "' cannot be opened (#128)");
    std::stringstream buf;
    buf << in.rdbuf();
    const std::string bytes = buf.str();
    FailureSchedule s;
    s.path = path;
    s.sha256 = Sha256Hex(bytes);
    std::istringstream lines(bytes);
    std::string line;
    uint32_t lineNo = 0;
    while (std::getline(lines, line)) {
        ++lineNo;
        const std::size_t hash = line.find('#');
        if (hash != std::string::npos) line.erase(hash);
        if (line.find_first_not_of(" \t\r") == std::string::npos) continue;
        std::istringstream ls(line);
        std::string t, target, op, extra;
        NS_ABORT_MSG_UNLESS((ls >> t >> target >> op) && !(ls >> extra),
                            path << ":" << lineNo
                                 << ": expected '<time> <node> start|shutdown|crash' or "
                                    "'<time> <a>-<b> down|up' (#128)");
        NS_ABORT_MSG_IF(s.events.size() >= kMaxFailureEvents,
                        path << ":" << lineNo << ": more than " << kMaxFailureEvents
                             << " events, the cap (kMaxFailureEvents, golden rule 7) (#128)");
        FailureEvent ev;
        ev.line = lineNo;
        char* end = nullptr;
        ev.time = std::strtod(t.c_str(), &end);
        NS_ABORT_MSG_UNLESS(end != t.c_str() && *end == '\0' && std::isfinite(ev.time) &&
                                ev.time >= 0.0 && ev.time < simTime,
                            path << ":" << lineNo << ": time '" << t
                                 << "' must be a number of seconds in [0, --time=" << simTime
                                 << ") (#128)");
        const std::size_t dash = target.find('-');
        if (dash != std::string::npos) {
            uint32_t a = 0, b = 0;
            NS_ABORT_MSG_UNLESS(ParseId(target.substr(0, dash), nNodes, a) &&
                                    ParseId(target.substr(dash + 1), nNodes, b) && a != b,
                                path << ":" << lineNo << ": link '" << target
                                     << "' must be two distinct node ids in [0, " << nNodes
                                     << ") (#128)");
            ev.a = std::min(a, b);
            ev.b = std::max(a, b);
            if (op == "down") {
                ev.op = FailureEvent::Op::kLinkDown;
            } else if (op == "up") {
                ev.op = FailureEvent::Op::kLinkUp;
            } else {
                NS_ABORT_MSG(path << ":" << lineNo << ": link op '" << op
                                  << "' must be down or up (#128)");
            }
        } else {
            NS_ABORT_MSG_UNLESS(ParseId(target, nNodes, ev.a),
                                path << ":" << lineNo << ": node '" << target
                                     << "' must be a node id in [0, " << nNodes << ") (#128)");
            if (op == "start") {
                ev.op = FailureEvent::Op::kStart;
            } else if (op == "shutdown") {
                ev.op = FailureEvent::Op::kShutdown;
            } else if (op == "crash") {
                ev.op = FailureEvent::Op::kCrash;
            } else {
                NS_ABORT_MSG(path << ":" << lineNo << ": node op '" << op
                                  << "' must be start, shutdown or crash (#128)");
            }
        }
        s.events.push_back(ev);
    }
    std::stable_sort(s.events.begin(), s.events.end(),
                     [](const FailureEvent& x, const FailureEvent& y) { return x.time < y.time; });
    // Every node and link starts up; each op must change its target's state.
    std::vector<bool> nodeDown(nNodes, false);
    std::set<std::pair<uint32_t, uint32_t>> linkDown;
    for (const FailureEvent& ev : s.events) {
        bool ok = true;
        switch (ev.op) {
        case FailureEvent::Op::kStart:
            ok = nodeDown[ev.a];
            nodeDown[ev.a] = false;
            break;
        case FailureEvent::Op::kShutdown:
        case FailureEvent::Op::kCrash:
            ok = !nodeDown[ev.a];
            nodeDown[ev.a] = true;
            break;
        case FailureEvent::Op::kLinkDown:
            ok = linkDown.insert({ev.a, ev.b}).second;
            break;
        case FailureEvent::Op::kLinkUp:
            ok = linkDown.erase({ev.a, ev.b}) == 1;
            break;
        }
        const bool link =
            ev.op == FailureEvent::Op::kLinkDown || ev.op == FailureEvent::Op::kLinkUp;
        NS_ABORT_MSG_UNLESS(ok, path << ":" << ev.line << ": " << OpName(ev.op) << " of "
                                     << (link ? "link " : "node ") << ev.a
                                     << (link ? "-" + std::to_string(ev.b) : std::string())
                                     << " at " << ev.time << " s, which is already "
                                     << (ev.op == FailureEvent::Op::kStart ||
                                                 ev.op == FailureEvent::Op::kLinkUp
                                             ? "up"
                                             : "down")
                                     << " (#128)");
    }
    return s;
}

NS_OBJECT_ENSURE_REGISTERED(FailureLossModel);

TypeId FailureLossModel::GetTypeId() {
    static TypeId tid = TypeId("ns3::bench::FailureLossModel")
                            .SetParent<PropagationLossModel>()
                            .SetGroupName("Propagation")
                            .AddConstructor<FailureLossModel>();
    return tid;
}

void FailureLossModel::SetNodes(uint32_t firstId, uint32_t n) {
    m_firstId = firstId;
    m_nodeCut.assign(n, false);
    m_linkCut.clear();
    m_cuts = 0;
}

void FailureLossModel::SetNodeCut(uint32_t node, bool cut) {
    if (node >= m_nodeCut.size() || m_nodeCut[node] == cut) return;
    m_nodeCut[node] = cut;
    cut ? ++m_cuts : --m_cuts;
}

void FailureLossModel::SetLinkCut(uint32_t a, uint32_t b, bool cut) {
    const std::pair<uint32_t, uint32_t> key{std::min(a, b), std::max(a, b)};
    if (cut ? m_linkCut.insert(key).second : m_linkCut.erase(key) == 1) cut ? ++m_cuts : --m_cuts;
}

bool FailureLossModel::IsCut(uint32_t a, uint32_t b) const {
    if (a >= m_nodeCut.size() || b >= m_nodeCut.size()) return false;
    return m_nodeCut[a] || m_nodeCut[b] || m_linkCut.count({std::min(a, b), std::max(a, b)}) > 0;
}

double FailureLossModel::DoCalcRxPower(double txPowerDbm, Ptr<MobilityModel> a,
                                       Ptr<MobilityModel> b) const {
    if (m_cuts == 0) return txPowerDbm;
    Ptr<Node> na = a ? a->GetObject<Node>() : nullptr;
    Ptr<Node> nb = b ? b->GetObject<Node>() : nullptr;
    if (!na || !nb) return txPowerDbm;
    // Ids below m_firstId wrap to large indices, which IsCut passes.
    return IsCut(na->GetId() - m_firstId, nb->GetId() - m_firstId) ? -1000.0 : txPowerDbm;
}

void InstallFailures(const std::vector<FailureEvent>& events, const NodeContainer& nodes,
                     Ptr<YansWifiChannel> channel, const std::vector<Ipv4Address>& addresses) {
    if (nodes.GetN() == 0) return;
    Ptr<FailureLossModel> cut = CreateObject<FailureLossModel>();
    cut->SetNodes(nodes.Get(0)->GetId(), nodes.GetN());
    PointerValue head;
    channel->GetAttribute("PropagationLossModel", head);
    Ptr<PropagationLossModel> tail = head.Get<PropagationLossModel>();
    if (!tail) {
        channel->SetPropagationLossModel(cut);
    } else {
        while (tail->GetNext()) tail = tail->GetNext();
        tail->SetNext(cut);
    }
    auto downed = std::make_shared<DownedInterfaces>(nodes.GetN());
    auto addrs = std::make_shared<const std::vector<Ipv4Address>>(addresses);
    for (const FailureEvent& ev : events) {
        Simulator::Schedule(Seconds(ev.time), [ev, nodes, cut, downed, addrs]() {
            ApplyFailure(ev, nodes, cut, downed, addrs);
        });
    }
}

