uint32_t RotR(uint32_t x, uint32_t n) {
    return (x >> n) | (x << (32 - n));
}

// A node id: decimal digits only, below nNodes.
bool ParseId(const std::string& text, uint32_t nNodes, uint32_t& out) {
    if (text.empty() || text.size() > 9 ||
        text.find_first_not_of("0123456789") != std::string::npos) {
        return false;
    }
    const unsigned long v = std::stoul(text);
    if (v >= nNodes) return false;
    out = static_cast<uint32_t>(v);
    return true;
}

const char* OpName(FailureEvent::Op op) {
    switch (op) {
    case FailureEvent::Op::kStart:
        return "start";
    case FailureEvent::Op::kShutdown:
        return "shutdown";
    case FailureEvent::Op::kCrash:
        return "crash";
    case FailureEvent::Op::kLinkDown:
        return "down";
    case FailureEvent::Op::kLinkUp:
        return "up";
    }
    return "?";
}

// The interfaces a shutdown or crash took down, per node, for its start.
using DownedInterfaces = std::vector<std::vector<uint32_t>>;

void ApplyFailure(const FailureEvent& ev, const NodeContainer& nodes, Ptr<FailureLossModel> cut,
                  std::shared_ptr<DownedInterfaces> downed,
                  const std::shared_ptr<const std::vector<Ipv4Address>>& addresses) {
    if (ev.op == FailureEvent::Op::kLinkDown || ev.op == FailureEvent::Op::kLinkUp) {
        cut->SetLinkCut(ev.a, ev.b, ev.op == FailureEvent::Op::kLinkDown);
        return;
    }
    Ptr<Node> node = nodes.Get(ev.a);
    Ptr<Ipv4> ip = node->GetObject<Ipv4>();
    std::vector<uint32_t>& mine = (*downed)[ev.a];
    if (ev.op == FailureEvent::Op::kStart) {
        cut->SetNodeCut(ev.a, false);
        for (uint32_t i : mine) ip->SetUp(i);
        mine.clear();
        return;
    }
    // shutdown, crash: off the channel, then off IP (NotifyInterfaceDown).
    cut->SetNodeCut(ev.a, true);
    for (uint32_t i = 0; ip && i < ip->GetNInterfaces(); ++i) {
        if (DynamicCast<LoopbackNetDevice>(ip->GetNetDevice(i)) || !ip->IsUp(i)) continue;
        ip->SetDown(i);
        mine.push_back(i);
    }
    if (ev.op != FailureEvent::Op::kCrash) return;
    // crash: the stack's volatile state goes too. Entries an arm made
    // permanent (hwmp's static ARP) or ns-3 auto-generated stay: they are
    // configuration, not learned state.
    Ptr<Ipv4L3Protocol> l3 = node->GetObject<Ipv4L3Protocol>();
    for (uint32_t i = 0; l3 && i < l3->GetNInterfaces(); ++i) {
        Ptr<ArpCache> arp = l3->GetInterface(i)->GetArpCache();
        if (!arp) continue;
        for (const Ipv4Address& addr : *addresses) {
            ArpCache::Entry* e = arp->Lookup(addr);
            if (e && !e->IsPermanent() && !e->IsAutoGenerated()) arp->Remove(e);
        }
    }
}

